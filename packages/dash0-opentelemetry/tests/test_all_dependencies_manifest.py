"""The dependency manifest the wheel ships beside ``sitecustomize.py``.

``sitecustomize.py`` reads ``all-dependencies.txt`` from its own directory and
deactivates the whole distribution when the application violates any line. The
file is generated by ``scripts/refresh_injector_manifest.py`` and checked in,
and CI fails when the two disagree, so these tests do not re-derive it. They
hold the properties the bootstrap depends on, and the three lines whose
wording was the reason for owning the format in the first place.
"""

from pathlib import Path

from dash0.opentelemetry.injector._packaging.requirements import Requirement
from dash0.opentelemetry.injector._packaging.version import Version

INJECTOR = Path(__file__).resolve().parents[1] / "src/dash0/opentelemetry/injector"
MANIFEST = INJECTOR / "all-dependencies.txt"


def requirement_for(name: str) -> Requirement:
    """The unmarked manifest line for one package, parsed as the bootstrap does."""
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        requirement = Requirement(line)
        if requirement.name == name and requirement.marker is None:
            return requirement
    raise AssertionError(f"{name} has no unmarked line in {MANIFEST.name}")


def test_the_manifest_sits_where_the_bootstrap_looks_for_it():
    """``join(dirname(__file__), "all-dependencies.txt")`` in ``read_dependencies``.

    The bootstrap resolves the path against its own directory, so the file has
    to ship inside the package rather than next to it.
    """
    assert MANIFEST.is_file()
    assert (INJECTOR / "sitecustomize.py").is_file()


def test_every_line_parses_with_the_vendored_packaging():
    """A line the bootstrap cannot parse is skipped with a warning.

    That is the quiet failure this guards: the package goes unchecked and
    nothing says so except one line on stderr.
    """
    lines = MANIFEST.read_text(encoding="utf-8").splitlines()

    assert lines
    for line in lines:
        requirement = Requirement(line)
        assert requirement.name == requirement.name.lower()
        requirement.specifier.contains(Version("1.0.0"))


def test_wrapt_accepts_what_opentelemetry_instrumentation_declares():
    """The regression the generator exists to stop.

    Consumers wrote one exact pin per installed package, so an application on
    ``wrapt`` 1.16 lost all telemetry even though
    ``opentelemetry-instrumentation`` declares ``<3.0.0,>=1.0.0``.
    """
    specifier = requirement_for("wrapt").specifier

    assert specifier.contains(Version("1.16.0"))
    assert specifier.contains(Version("1.17.3"))
    assert not specifier.contains(Version("2.0.0"))


def test_pyyaml_is_unconstrained():
    """``UNPINNED_BY_DESIGN`` in ``scripts/check_pinned_dependencies.py``.

    Only the distribution's own packages require ``pyyaml``, and they pin it,
    so every constraint on it is curation. Leaving the line bare is what makes
    the exemption reach the bootstrap rather than stopping at the pyproject
    file.
    """
    assert not requirement_for("pyyaml").specifier


def test_opentelemetry_sdk_is_constrained_without_being_pinned():
    """Every distribution declaring the SDK carries the ``dash0-`` prefix.

    Skipping all of them left the line bare, which let an application running
    any SDK version at all keep the distribution active. Skipping only their
    exact pins keeps the ``~=1.12`` the vendored pyproto exporters declare.
    """
    specifier = requirement_for("opentelemetry-sdk").specifier

    assert specifier.contains(Version("1.44.0"))
    assert specifier.contains(Version("1.45.1"))
    assert not specifier.contains(Version("1.11.0"))
    assert not specifier.contains(Version("2.0.0"))
